# Ορισμός του ονόματος του εκτελέσιμου (αντικαταστήστε με test_main αν είναι άλλο)
EXECUTABLE="./test_main"

# Ορισμός των ορισμάτων
# Ορισμός των τιμών για τον βαθμό του πολυωνύμου (n)
N_VALUES=(10 100 1000 10000 100000)

# Ορισμός των τιμών για τον αριθμό των νημάτων (P)
P_VALUES=(1 2 4 8 16)

# ΟΡΙΣΜΟΣ ΚΑΙ ΚΑΘΑΡΙΣΜΟΣ ΤΟΥ ΑΡΧΕΙΟΥ ΕΞΟΔΟΥ
OUTPUT_FILE="1.1.txt"
> "$OUTPUT_FILE" # Μηδενίζει το αρχείο πριν την έναρξη

(echo "---") | tee -a "$OUTPUT_FILE"

for N in "${N_VALUES[@]}"; do
    for P in "${P_VALUES[@]}"; do
            (
                echo "Εκτέλεση $i με n=${N}, P=${P}"
                
                # Εκτέλεση του προγράμματος με τα ορίσματα N και P
                "$EXECUTABLE" "$N" "$P"
                
                echo "---"
            ) | tee -a "$OUTPUT_FILE"
    done
done

echo "--- Όλες οι εκτελέσεις ολοκληρώθηκαν. ---" | tee -a "$OUTPUT_FILE"